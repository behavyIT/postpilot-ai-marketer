"""Исключения прикладного уровня.

Сервисы бросают эти исключения, а слой представления (бот, API) превращает их
в понятные пользователю сообщения. Текст исключения пишется по-русски и может
показываться пользователю как есть.
"""

from __future__ import annotations


class AppError(Exception):
    """Базовая ошибка приложения."""


class NotFoundError(AppError):
    """Объект не найден или недоступен текущему пользователю.

    Для чужих объектов намеренно используется та же ошибка, что и для несуществующих,
    чтобы не раскрывать факт их существования.
    """


class AccessDeniedError(AppError):
    """Действие запрещено для текущего пользователя."""


class DomainValidationError(AppError):
    """Входные данные нарушают бизнес-правила."""
